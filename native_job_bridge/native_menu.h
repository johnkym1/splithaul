// Read-only main-menu detection for the exact cancellation builds.
// Convoy does not emit the SDK pause event when the desktop opens.
// Evidence: research/convoy-cancellation-20261126/static-layout.json.
#ifdef GT_TARGET_ETS2
static constexpr uintptr_t desktopVisibilityRva=0x380630,desktopVtableRva=0x22a5508;
#else
static constexpr uintptr_t desktopVisibilityRva=0x381300,desktopVtableRva=0x22a7508;
#endif
static constexpr unsigned char desktopVisibilityCode[]={0x40,0x53,0x48,0x83,0xec,0x20,0x8b,0x51,0x60,0x48,0x8b,0xd9,0x8b,0xc2,0x25,0x00,0x00,0x00,0x30,0x3d,0x00,0x00,0x00,0x20,0x75,0x5f,0x0f,0xba,0xe2,0x1b,0x73,0x45,0x48,0x8b,0x41,0x50,0x48,0x85,0xc0,0x74,0x39,0x8b,0x40,0x08,0xc1,0xe8,0x1f,0x84,0xc0,0x74,0x2f,0x48,0x8b,0x49,0x50,0xe8,0xc4,0xff,0xff,0xff,0xf6,0xd8,0x8b,0x43,0x60,0x1b,0xd2,0x25,0xff,0xff,0xff,0xcf,0x81,0xe2,0x00,0x00,0x00,0x10,0x0b,0xd0,0xf7,0xc2,0x00,0x00,0x00,0x30,0x89,0x53,0x60,0x0f,0x95,0xc0,0x48,0x83,0xc4,0x20,0x5b,0xc3,0x8b,0x51,0x60,0x8b,0xc2,0x81,0xe2,0x00,0x00,0x00,0x08,0x03,0xd2,0x25,0xff,0xff,0xff,0xcf,0x0b,0xd0,0x89,0x51,0x60,0xf7,0xc2,0x00,0x00,0x00,0x30,0x0f,0x95,0xc0,0x48,0x83,0xc4,0x20,0x5b,0xc3};
static bool nativeDesktopMenuOpen() {
    const auto* build=activeCancellationBuild();
    unsigned char code[sizeof(desktopVisibilityCode)]={};
    uintptr_t desktop=0,vtable=0,screen=0,name=0;uint32_t flags=0;char label[8]={};
    if(!build||!readMemory(imageBase+desktopVisibilityRva,code,sizeof(code))||memcmp(code,desktopVisibilityCode,sizeof(code)))return false;
    if(!word(imageBase+build->otherRoot,desktop)||!liveUnit(desktop)||!word(desktop,vtable)||vtable!=imageBase+desktopVtableRva||!word(desktop+0xe0,screen)||!liveUnit(screen))return false;
    if(!word(screen+0xa0,name)||!readMemory(name,label,sizeof(label))||memcmp(label,"desktop",sizeof(label))||!readMemory(screen+0x60,&flags,sizeof(flags)))return false;
    // The game caches visibility in bits 28-29. 0x2 is unresolved/dirty,
    // not proof of visibility. Accept only resolved visible (0x1).
    return (flags&0x30000000u)==0x10000000u;
}
